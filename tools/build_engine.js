// Builds the PokeSquad engine for the Showdown server fork (the owner's pick, 2026-10-19: a real Showdown server running PokeSquad's
// own battles). The game's parts up to the battle engine (build.sh's BODY order, up to a7_engine.js, without the embedded pictures
// and sounds) and tools/showdown_adapter.js, as one plain script. The fork's server/pokesquad.ts runs it in a sandbox with stand-ins
// for the browser. Written to showdown/server/pokesquad/engine.js when the fork is checked out there (its own repo,
// Mikale4/PokeSquad-Showdown), else to dist/pokesquad-engine.js. build.sh runs this after every build; never edit the output.
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const body = fs.readFileSync(path.join(root, "src", "build.sh"), "utf8").match(/BODY="([^"]+)"/)[1].split(" ");
const parts = body.slice(0, body.indexOf("src/a7_engine.js") + 1).filter(p => !["dist/res.js", "dist/sprites.js"].includes(p));
let out = "// PokeSquad Battler's battle engine for the Showdown server: generated by tools/build_engine.js from the game's src/. Never edit.\n";
for (const p of parts) {
  let src = fs.readFileSync(path.join(root, p), "utf8");
  if (p === "src/a2_core.js") src = src.slice(src.indexOf("<script>") + 8);   // (its page markup stays in the game)
  out += `\n// ---------- ${p} ----------\n` + src.replace(/<\/?script>/g, "");
}
out += "\n// ---------- tools/showdown_adapter.js ----------\n" + fs.readFileSync(path.join(__dirname, "showdown_adapter.js"), "utf8");
const fork = path.join(root, "showdown", "server");
const dest = fs.existsSync(fork) ? path.join(fork, "pokesquad", "engine.js") : path.join(root, "dist", "pokesquad-engine.js");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(root, dest)} (${Math.round(out.length / 1024)} KB)`);
