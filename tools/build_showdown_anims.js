// Generates src/a8d_showdown.js from Pokémon Showdown's animation scripts (resources/showdown/src, fetched by
// tools/fetch_showdown_anims.py): BattleMoveAnims (every move's animation), BattleEffects (the effect pictures and their
// sizes), BattleOtherAnims and BattleStatusAnims (shared and status animations), as they are, only their TypeScript
// types taken out. They run on the Showdown-style stage in src/a8e_showdown_scene.js. Never edit the output.
//   node tools/build_showdown_anims.js
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, "..");
const src = f => fs.readFileSync(path.join(root, "resources", "showdown", "src", f), "utf8");
// the little TypeScript these files use
const untype = s => s
  .replace(/^import .*$/gm, "")
  .replace(/^export (const|function|class|type|interface)/gm, "$1")
  .replace(/^(const \w+): [^=\n]+ = /gm, "$1 = ")                         // const X: Type = ...
  .replace(/\b((?:const|let|var) \w+): [A-Za-z][^=;\n]*?(?= = )/g, "$1")  // let x: Type = ...
  .replace(/^(\s*let [^=\n]*;)$/gm, l => l.replace(/(\w+): [A-Za-z][\w.<>[\]|]*/g, "$1"))   // let a: T, b: T;
  .replace(/\bas \[[^\]]*\]/g, "")                                        // ... as [string, JQuery.PlainObject]
  .replace(/\bas (?:const|any|[A-Z]\w*(?:\[\])?)\b/g, "")                 // ... as const / as any / as Type
  .replace(/\b(null|\w+)!(?=[\s.,;)\]?:])/g, "$1");                       // non-null assertions: x!, null!
const moves = src("battle-animations-moves.ts"), eng = src("battle-animations.ts");
const cut = (s, a, b) => { const i = s.indexOf(a); if (i < 0) throw new Error("not found: " + a); const j = b ? s.indexOf(b, i) : s.length; if (j < 0) throw new Error("not found: " + b); return s.slice(i, j); };
const effects = cut(eng, "const BattleEffects", "\n(() => {");
const others = cut(eng, "export const BattleOtherAnims");
let out = `// =====================================================================
//  POKÉMON SHOWDOWN'S BATTLE ANIMATIONS — generated by tools/build_showdown_anims.js. Do not edit by hand.
//  From smogon/pokemon-showdown-client (${fs.readFileSync(path.join(root, "resources", "showdown", "SOURCE.txt"), "utf8").split(/\r?\n/)[0].replace(/^.* at /, "commit ")}):
//  battle-animations-moves.ts (CC0) and, from battle-animations.ts (MIT), the effect table and the shared and status
//  animations. They run on src/a8e_showdown_scene.js; the pictures are resources/showdown/fx (RES_DATA.psfx).
// =====================================================================
`;
out += untype(effects) + "\n" + untype(others) + "\n" + untype(moves) + "\n";
// interface and type declarations left over from the engine file
out = out.replace(/^(?:interface|type) \w+[^\n]*\{[\s\S]*?^\}\n/gm, "").replace(/^type \w+ = [^\n]*\n/gm, "");
new vm.Script(out, { filename: "a8d_showdown.js" });   // (it has to parse as plain JavaScript)
fs.writeFileSync(path.join(root, "src", "a8d_showdown.js"), out);
const n = (out.match(/^\t[a-z0-9]+: \{/gm) || []).length;
console.log("wrote src/a8d_showdown.js:", Math.round(out.length / 1024), "KB,", n, "table entries");
