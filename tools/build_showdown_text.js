// Generates src/a3c_showdown_text.js: Pokémon Showdown's battle text (smogon/pokemon-showdown data/text, MIT), the
// messages the main games show, for the battle engine's messages (psT in a7_engine.js). Only the in-battle lines of
// today's games are kept (no names, descriptions or older generations' wording); "#move" references (a line that's the
// same as another move's) are looked up. The text files are fetched into resources/showdown/text by
// tools/fetch_showdown_anims.py.   node tools/build_showdown_text.js
const fs = require("fs"), path = require("path"), vm = require("vm");
const root = path.join(__dirname, ".."), dir = path.join(root, "resources", "showdown", "text");
// each file is one exported object literal: read it as data in a sandbox (nothing else is in scope)
const load = f => {
  const s = fs.readFileSync(path.join(dir, f), "utf8").replace(/^export const \w+: [^=]+= /m, "module.exports = ");
  const box = { module: {} }; vm.runInNewContext(s, box, { timeout: 5000 }); return box.module.exports;
};
const T = { default: load("default.ts"), moves: load("moves.ts"), abilities: load("abilities.ts"), items: load("items.ts") };
const SKIP = new Set(["name", "desc", "shortDesc"]);
const out = {};
for (const [tbl, data] of Object.entries(T)) {
  out[tbl] = {};
  for (const [id, e] of Object.entries(data)) {
    const keep = {};
    for (const [k, v] of Object.entries(e)) if (!SKIP.has(k) && !/^gen\d$/.test(k) && typeof v === "string") keep[k] = v;
    if (Object.keys(keep).length) out[tbl][id] = keep;
  }
}
// "#id": the same line as entry id has (moves first, then Abilities, items, the defaults)
for (const tbl of Object.keys(out)) for (const e of Object.values(out[tbl])) for (const [k, v] of Object.entries(e)) {
  if (!v.startsWith("#")) continue;
  const ref = v.slice(1), src = ["moves", "abilities", "items", "default"].map(t => out[t][ref]).find(x => x && x[k] && !x[k].startsWith("#"));
  if (src) e[k] = src[k]; else delete e[k];
}
const sha = fs.existsSync(path.join(dir, "SOURCE.txt")) ? fs.readFileSync(path.join(dir, "SOURCE.txt"), "utf8").split(/\r?\n/)[0] : "";
const js = `// =====================================================================
//  POKÉMON SHOWDOWN'S BATTLE TEXT — generated by tools/build_showdown_text.js. Do not edit by hand.
//  From smogon/pokemon-showdown data/text (MIT; ${sha}): the main games' battle messages, today's wording.
//  {POKEMON}, {TEAM}, {SOURCE}, {MOVE}, {ITEM}, {STAT}... are filled in by psT (a7_engine.js).
// =====================================================================
const PS_TEXT = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(root, "src", "a3c_showdown_text.js"), js);
console.log("wrote src/a3c_showdown_text.js:", Math.round(js.length / 1024), "KB;", Object.entries(out).map(([t, o]) => `${t} ${Object.keys(o).length}`).join(", "));
